// Builds public/app/index.html (the app) and public/assets/figure.js (the animated figure for the sales page)
// from the files in src/. Runs on every Vercel deploy; you can also run it with: node scripts/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const engine = read('src/engine.js');
const exlib = read('src/ex.js') + '\n' + read('src/ex_en.js');
let app = read('src/app.js');

// Small changes so the app shows real progress instead of the prototype's sample numbers.
const patches = [
  ['${doneInMonth * 18 + S.todayMinutes}', '${monthMinutes()}'],
  ['${18 + S.sessions}', '${S.sessions}'],
  ['<div class="bdg"><span class="ic" style="background:var(--plum-soft);color:var(--plum)">${I.logo}</span>${t(\'r.first\')}</div>',
   '${S.sessions >= 1 ? `<div class="bdg"><span class="ic" style="background:var(--plum-soft);color:var(--plum)">${I.logo}</span>${t(\'r.first\')}</div>` : `<div class="bdg locked"><span class="ic" style="background:var(--white);color:var(--muted-2)">${I.lock}</span>${t(\'r.first\')}</div>`}'],
  ['<div class="bdg"><span class="ic" style="background:var(--peach);color:var(--peach-ink)">${I.flameL}</span>${t(\'r.seven\')}</div>',
   '${S.best >= 7 ? `<div class="bdg"><span class="ic" style="background:var(--peach);color:var(--peach-ink)">${I.flameL}</span>${t(\'r.seven\')}</div>` : `<div class="bdg locked"><span class="ic" style="background:var(--white);color:var(--muted-2)">${I.lock}</span>${t(\'r.seven\')}</div>`}'],
];
for (const [from, to] of patches) {
  if (!app.includes(from)) throw new Error('build: could not find text to patch: ' + from.slice(0, 60));
  app = app.replace(from, to);
}
// The prototype draws its first screen right away; the real app waits for the login check (src/prod.js).
const last = app.lastIndexOf('render(false);');
if (last === -1) throw new Error('build: final render call not found');
app = app.slice(0, last) + app.slice(last + 'render(false);'.length);

const html = read('src/app-shell.html')
  .replace('/*CSS*/', () => read('src/app.css') + '\na.btn{text-decoration:none}')
  .replace('/*ENGINE*/', () => engine)
  .replace('/*EXLIB*/', () => exlib)
  .replace('/*APP*/', () => app)
  .replace('/*PROD*/', () => read('src/prod.js'));
writeFileSync(join(root, 'public/app/index.html'), html);

const figure = `/* Generated by scripts/build.mjs from src/engine.js and src/ex*.js. Do not edit by hand. */
(function(){
'use strict';
${engine}
${exlib}
window.AiraFig = { figure, mix, ease, EX };
})();
`;
writeFileSync(join(root, 'public/assets/figure.js'), figure);
// Class list + first-week planner, shared by the quiz page and the server (follow-up e-mails).
const appSrc = read('src/app.js');
const a0 = appSrc.indexOf('const CLASSES = {'), a1 = appSrc.indexOf('function adaptEx(');
if (a0 === -1 || a1 === -1) throw new Error('build: CLASSES block not found in src/app.js');
const box = {};
vm.createContext(box);
vm.runInContext(appSrc.slice(a0, a1).replace(/^const /gm, 'var '), box);
const classes = {};
for (const [id, C] of Object.entries(box.CLASSES)) {
  classes[id] = { title: C.title, mod: C.mod, level: C.level, min: C.min, hero: C.hero, en: { title: C.en.title } };
  if (C.fixed) classes[id].fixed = true;
}
const goals = box.GOALS.map((g) => ({ id: g.id, label: g.label, en: { label: g.en.label }, cls: g.cls }));
const data = `const CLASSES = ${JSON.stringify(classes)};\nconst GOALS = ${JSON.stringify(goals)};\n`;
const plan = read('src/plan.js');
writeFileSync(join(root, 'public/assets/classes.js'), `/* Generated by scripts/build.mjs from src/app.js and src/plan.js. Do not edit by hand. */\n(function(){\n'use strict';\n${data}${plan}\nwindow.AiraPlan = { CLASSES, GOALS, QUIZ_LABELS, AREA_GOAL, quizGoals, firstWeek };\n})();\n`);
writeFileSync(join(root, 'lib/classes.js'), `/* Generated by scripts/build.mjs from src/app.js and src/plan.js. Do not edit by hand. */\n${data}${plan}\nexport { CLASSES, GOALS, QUIZ_LABELS, AREA_GOAL, quizGoals, firstWeek };\n`);

console.log('Built public/app/index.html (' + Math.round(html.length / 1024) + ' KB), public/assets/figure.js and classes.js, lib/classes.js');
